import importlib.util
from pathlib import Path

import pytest

PATH = (
    Path(__file__).resolve().parents[1]
    / "skills"
    / "gha-hardening"
    / "scripts"
    / "compare_locks.py"
)
spec = importlib.util.spec_from_file_location("compare_locks", PATH)
compare_locks = importlib.util.module_from_spec(spec)
spec.loader.exec_module(compare_locks)
parse = compare_locks.parse

UV_LOCK_WITHOUT_GIT = """
version = 1
revision = 3

[[package]]
name = "app"
version = "0.1.0"
source = { editable = "." }
dependencies = [{ name = "click" }]

[[package]]
name = "click"
version = "8.1.8"
source = { registry = "https://pypi.org/simple" }
dependencies = [{ name = "colorama", marker = "sys_platform == 'win32'" }]

[[package]]
name = "colorama"
version = "0.4.6"
source = { registry = "https://pypi.org/simple" }
"""
UV_LOCK = (
    UV_LOCK_WITHOUT_GIT
    + """
[[package]]
name = "flare"
version = "0.1.0"
source = { git = "ssh://git@github.com/Giskard-AI/flare.git#75c36ee3aaaabbbbccccdddd" }
"""
)
COLORAMA_ADDED = "added    colorama 0.4.6 (platform-only: sys_platform == 'win32')"

POETRY_LOCK = """
[[package]]
name = "Click"
version = "8.1.8"
optional = false

[package.dependencies]
colorama = {version = "*", markers = "platform_system == \\"Windows\\""}

[[package]]
name = "flare"
version = "0.1.0"

[package.source]
type = "git"
url = "https://github.com/Giskard-AI/flare.git"
reference = "main"
resolved_reference = "6a24ee4db35ee1808f7ba264456a424b79200777"
"""

RYE_LOCK = """# generated by rye
-e file:.
click==8.1.8
    # via app
typing_extensions==4.12.2 ; python_version < "3.13"
uvicorn[standard]==0.34.0 \\
    --hash=sha256:abc
"""

PIPFILE_LOCK = '{"_meta": {}, "default": {"click": {"version": "==8.1.8"}}, "develop": {"pytest": {"version": "==8.3.4"}}}'  # noqa: E501


@pytest.mark.parametrize(
    ("text", "versions"),
    [
        pytest.param(UV_LOCK, {"click": {"8.1.8"}, "colorama": {"0.4.6"},
                               "flare": {"0.1.0 (git 75c36ee3)"}}, id="uv-lock"),
        pytest.param(POETRY_LOCK, {"click": {"8.1.8"}, "flare": {"0.1.0 (git 6a24ee4d)"}},
                     id="poetry-lock-git-and-case"),
        pytest.param(RYE_LOCK, {"click": {"8.1.8"}, "typing-extensions": {"4.12.2"},
                                "uvicorn": {"0.34.0"}}, id="rye-requirements-lock"),
        pytest.param(PIPFILE_LOCK, {"click": {"8.1.8"}, "pytest": {"8.3.4"}}, id="pipfile-lock"),
    ],
)  # fmt: skip
def test_parse_versions(text, versions):
    assert parse(text).versions == versions


@pytest.mark.parametrize(
    ("text", "local", "platform_only"),
    [
        pytest.param(UV_LOCK, {"app"}, {"colorama": {"sys_platform == 'win32'"}},
                     id="uv-root-is-local-colorama-is-platform-only"),
        pytest.param(POETRY_LOCK, set(), {}, id="poetry-has-no-edge-markers"),
    ],
)  # fmt: skip
def test_parse_local_and_platform_only(text, local, platform_only):
    lock = parse(text)
    assert (lock.local, lock.platform_only) == (local, platform_only)


@pytest.mark.parametrize(
    ("old", "new", "lines", "moved"),
    [
        pytest.param(RYE_LOCK, RYE_LOCK, [], False, id="identical"),
        pytest.param("click==8.1.8\n", UV_LOCK_WITHOUT_GIT, [COLORAMA_ADDED], False,
                     id="only-a-platform-only-addition"),
        pytest.param("click==8.1.8\n", UV_LOCK,
                     [COLORAMA_ADDED, "added    flare 0.1.0 (git 75c36ee3)"], True,
                     id="platform-only-beside-a-real-addition"),
        pytest.param("click==8.1.8\ncolorama==0.4.6\nflare==0.1.0\n", "click==8.1.8\n",
                     ["removed  colorama 0.4.6", "removed  flare 0.1.0"], True, id="removed"),
        pytest.param(POETRY_LOCK, UV_LOCK,
                     [COLORAMA_ADDED,
                      "changed  flare 0.1.0 (git 6a24ee4d) -> 0.1.0 (git 75c36ee3)"],
                     True, id="git-commit-moved"),
    ],
)  # fmt: skip
def test_compare(old, new, lines, moved):
    assert compare_locks.compare(parse(old), parse(new)) == (lines, moved)
